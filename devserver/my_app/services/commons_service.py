_TAG_RE = re.compile(r"<[^>]+>")
_WS_RE = re.compile(r"\s+")
# Keep letters and digits in ANY script, drop everything else. An ASCII-only
# allowlist turned "полярний ведмідь" into nothing and "Eisbär" into "eisb r",
# then reported that as a finding about the prompt. What the filter is FOR is
# CirrusSearch syntax — colon, quote, tilde, ampersand — and none of those is a
# word character, so \w still shuts the injection out.
_TERM_SAFE_RE = re.compile(r"[^\w \-]", re.UNICODE)
_ANGLE_RE = re.compile(r"[<>]")


