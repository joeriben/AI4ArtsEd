"""
Wikimedia Commons service — the comparison horizon under the model grid.

What this is for
----------------
The Model Comparison tab holds the prompt still and swaps the image model. This
service adds one more column of images that were NOT generated: it reduces the
prompt to a short search term, asks Wikimedia Commons for up to three files, and
returns them with the provenance every tile has to carry (author, licence, file
description page).

Three rules the caller must not lose:

* **We fetch, the browser does not.** The returned ``thumb_proxy`` points at our
  own origin (``/api/commons/image``); the raw Wikimedia URL is only used
  server-side. Embedding ``upload.wikimedia.org`` directly would make the
  participants' browsers talk to Wikimedia on page load, which the design
  rules out.

* **Serving a file from our origin makes it ours.** Wikimedia keeps user-uploaded
  SVG on a separate host precisely because an SVG is a scriptable document, and
  it sends a restrictive CSP with it. A proxy that echoes the upstream type would
  hand an attacker a page on the institution's own domain. Hence
  ``ALLOWED_IMAGE_TYPES``: raster formats only, no negotiation, and the route
  adds its own CSP on top.

* **Commons holds AI-generated images.** Categories such as "Images generated by
  Midjourney" exist and a search can return them; a generated image in the
  found-images row would cancel the very difference the row is built on. Three
  layers, because no one of them holds: the query excludes the categories that
  actually carry the bulk (``-incategory:`` matches DIRECT membership only, so
  naming the parent category excludes almost nothing); every returned file is
  then checked against its own categories AND its licence (``PD-algorithm`` is
  the Commons tag for a work with no human author, and 72 % of a 150-file sample
  from it carried no AI category at all); and the tile shows the file's
  categories, so a slip-through is visible in the room instead of silent.

* **Commons is not age-filtered, and the search API has no safe-search.** A term
  as ordinary as "mirror selfie" returns explicit photographs that pass every
  test above. At kids and youth two things therefore stand in front of the row:
  the file's own Commons categories are screened, and then the picture goes
  through the platform's own image check — the same ``vlm_safety_check`` the
  upload path uses — fail-closed.

  Both are needed and neither is sufficient. Measured on 2026-08-17: for
  "Mirror selfie with visible male genital.jpg" the describing model wrote
  "wearing a grey Adidas zip-up hoodie and dark jeans", so the classifier passed
  a description with the subject left out; the file's categories name it. The
  categories in turn are only as good as Commons' own cataloguing.

Empty results are ordinary answers here, failures are not. ``no_motif`` means the
prompt only changes an existing image ("make the sky purple") and names nothing
that could be looked up — 11 % of the prompts in the workshop data of
2026-03-22. ``nothing_found`` means the archive has nothing for the term.
``error`` means WE could not ask, and it is kept strictly apart from the other
two: an exhausted model chain must never reach the room as a statement about a
participant's prompt.

API: Commons runs the same MediaWiki ``api.php`` that wikipedia_service.py
already talks to (``:226``), on a different host and with different actions.
"""

