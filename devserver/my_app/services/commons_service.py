class _TTLCache:
    """Small thread-safe TTL cache with a hard entry cap.

    The cap is not tidiness. Both callers key on attacker-supplied strings from
    an unauthenticated route, and expiry alone only ever fires on a repeat hit
    of the same key — so without a cap a stream of unique prompts grows the heap
    without bound. When the cap is reached the oldest entries go.
    """

    def __init__(self, ttl_seconds: int = 3600, max_entries: int = 512) -> None:
        self._ttl = ttl_seconds
        self._max = max_entries
        self._data: Dict[str, Tuple[float, Any]] = {}
        self._lock = threading.Lock()

    def get(self, key: str) -> Optional[Any]:
        with self._lock:
            hit = self._data.get(key)
            if not hit:
                return None
            stamp, value = hit
            if time.time() - stamp > self._ttl:
                del self._data[key]
                return None
            return value

    def set(self, key: str, value: Any) -> None:
        with self._lock:
            if len(self._data) >= self._max and key not in self._data:
                now = time.time()
                for stale in [k for k, (s, _) in self._data.items()
                              if now - s > self._ttl]:
                    del self._data[stale]
                while len(self._data) >= self._max:
                    oldest = min(self._data, key=lambda k: self._data[k][0])
                    del self._data[oldest]
            self._data[key] = (time.time(), value)

    def clear(self) -> None:
        with self._lock:
            self._data.clear()


_search_cache = _TTLCache(ttl_seconds=3600)
_term_cache = _TTLCache(ttl_seconds=3600)


def _clean_term(raw: str) -> Tuple[Optional[str], str]:
    """Normalise the model's answer into ``(term, status)``.

    ``status`` is ``TERM_OK``, ``TERM_NO_MOTIF`` (the model said the prompt names
    no motif) or ``TERM_UNAVAILABLE`` (the answer is not a term — empty, or prose
    about the task). The third is not a statement about the prompt.
    """
    text = _WS_RE.sub(" ", (raw or "")).strip()
    if not text:
        return None, TERM_UNAVAILABLE
    # Models like to wrap short answers in quotes or add a trailing period.
    text = text.strip('"“”‘’\'').strip().rstrip(".")
    # Matched with the underscore normalised away: a model that writes "no motif"
    # instead of the sentinel would otherwise be searched for, and Commons
    # answers it with screenshots of the Motif window manager.
    if "no motif" in text.lower().replace("_", " "):
        return None, TERM_NO_MOTIF
    text = _TERM_SAFE_RE.sub(" ", text.lower()).replace("_", " ")
    text = _WS_RE.sub(" ", text).strip()
    if not text:
        return None, TERM_UNAVAILABLE
    words = text.split(" ")
    if len(words) > MAX_ANSWER_WORDS:
        logger.warning(f"[COMMONS] Answer is prose, not a term: {text[:80]!r}")
        return None, TERM_UNAVAILABLE
    if len(words) > 1 and words[0] in LEADING_ARTICLES:
        words = words[1:]
    if any(word in PROSE_MARKERS for word in words):
        logger.warning(f"[COMMONS] Answer is prose, not a term: {text[:80]!r}")
        return None, TERM_UNAVAILABLE
    if not words:
        return None, TERM_UNAVAILABLE
    # A subject phrase: "dog on a street" is four words, its function words cost
    # nothing in the query, and the phrase reads as something a person would type.
    return " ".join(words[:4]), TERM_OK


def derive_search_term(prompt: str) -> Tuple[Optional[str], str]:
    """Reduce a prompt to a one-to-three-word archive query.

    Returns ``(term, status)``. ``TERM_NO_MOTIF`` is an ordinary outcome — a
    change instruction names nothing to look for. ``TERM_UNAVAILABLE`` means we
    could not ask, or did not get a term back; that is our failure and is said as
    such rather than as a finding about the prompt.
    """
    text = (prompt or "").strip()
    if not text:
        return None, TERM_NO_MOTIF
    if len(text) > MAX_PROMPT_CHARS:
        logger.warning(f"[COMMONS] Prompt too long ({len(text)} chars) — not asking")
        return None, TERM_UNAVAILABLE

    cached = _term_cache.get(text)
    if cached is not None:
        return (cached, TERM_OK) if cached else (None, TERM_NO_MOTIF)

    # call_chat_helper is the entry point every service uses: it reads the role
    # from the user settings, builds the fallback chain and honours the DSGVO
    # gate. Going through LLMService would post straight at the GPU service and
    # miss every cloud model the role may be set to.
    try:
        from my_app.routes.chat_routes import call_chat_helper
        # max_tokens stays unset: the reply is a few words, and a cap here would
        # be the exact failure mode the project forbids.
        result = call_chat_helper(
            messages=[
                {"role": "system", "content": TERM_SYSTEM},
                {"role": "user",
                 "content": f"{TERM_EXAMPLES}\nInput: {text}\nSearch term:"},
            ],
            temperature=0.0,
            enable_thinking=False,
            role="CHAT_HELPER_MODEL",
        )
    except Exception as exc:  # noqa: BLE001 - any failure here is "could not ask"
        logger.error(f"[COMMONS] Term derivation failed: {exc}")
        return None, TERM_UNAVAILABLE

    answer = (result or {}).get("content") or ""
    term, status = _clean_term(answer)
    # Only a real answer is remembered. Caching a failure would pin an outage to
    # this prompt for the whole hour, long after the provider came back.
    if status == TERM_OK:
        _term_cache.set(text, term)
        logger.info(f"[COMMONS] Term for prompt: {term!r}")
    elif status == TERM_NO_MOTIF:
        _term_cache.set(text, "")
        logger.info("[COMMONS] Prompt names no motif")
    return term, status


def _strip_html(value: str) -> str:
    """Flatten an extmetadata field to plain text.

    ``Artist`` is usually a link and is editable by anyone on Commons. Unescape
    FIRST, then remove tags, then remove any bare angle bracket that is left:
    the other order turns ``&lt;img onerror=...&gt;`` back into live markup after
    the tag filter has already run.
    """
    text = html.unescape(value or "")
    text = _TAG_RE.sub(" ", text)
    text = _ANGLE_RE.sub(" ", text)
    return _WS_RE.sub(" ", text).strip()


def _is_ai_generated(categories: List[str]) -> bool:
    joined = " | ".join(c.lower() for c in categories)
    return any(marker in joined for marker in AI_CATEGORY_MARKERS)


def _is_explicit(categories: List[str]) -> bool:
    """Whether the file's own Commons categories mark it as unsuitable."""
    joined = " | ".join(c.lower() for c in categories)
    return any(marker in joined for marker in EXPLICIT_CATEGORY_MARKERS)


def encode_image_ref(url: str) -> str:
    """Pack a Wikimedia thumbnail URL for our own proxy route."""
    return base64.urlsafe_b64encode(url.encode("utf-8")).decode("ascii").rstrip("=")


def decode_image_ref(ref: str) -> Optional[str]:
    """Unpack and validate a proxy reference.

    ``None`` for anything that is not an https URL on an allowed Wikimedia host
    and port. ``urlparse`` itself raises on malformed authorities (``https://[::1``,
    a fullwidth ``#``), so it is inside the guard — outside it, a forged
    reference answered 500 instead of 400.
    """
    try:
        padded = ref + "=" * (-len(ref) % 4)
        url = base64.urlsafe_b64decode(padded.encode("ascii")).decode("utf-8")
        parsed = urllib.parse.urlparse(url)
        host = parsed.hostname
        port = parsed.port
    except (binascii.Error, UnicodeDecodeError, ValueError):
        return None
    if parsed.scheme != "https":
        return None
    if host not in ALLOWED_IMAGE_HOSTS or port not in ALLOWED_IMAGE_PORTS:
        return None
    return url


def fetch_image_bytes(url: str) -> Optional[Tuple[bytes, str]]:
    """Load one thumbnail server-side. The browser never talks to Wikimedia.

    Redirects are NOT followed: the allowlist in ``decode_image_ref`` only ever
    sees the first hop, so a redirect would carry the request to a host and
    scheme nobody checked and hand the answer straight back to the browser.

    The body is streamed and capped. Without that, the type check below runs
    only after a multi-gigabyte file is already resident.
    """
    try:
        response = requests.get(url, headers={"User-Agent": USER_AGENT},
                                timeout=HTTP_TIMEOUT, stream=True,
                                allow_redirects=False)
        with response:
            if response.status_code != 200:
                logger.warning(f"[COMMONS] Thumbnail answered {response.status_code}")
                return None

            content_type = (response.headers.get("Content-Type") or "").split(";")[0].strip().lower()
            if content_type not in ALLOWED_IMAGE_TYPES:
                logger.warning(f"[COMMONS] Refused content type {content_type!r}")
                return None

            declared = response.headers.get("Content-Length")
            if declared and declared.isdigit() and int(declared) > MAX_IMAGE_BYTES:
                logger.warning(f"[COMMONS] Refused oversized file ({declared} bytes)")
                return None

            chunks: List[bytes] = []
            size = 0
            for chunk in response.iter_content(chunk_size=64 * 1024):
                size += len(chunk)
                if size > MAX_IMAGE_BYTES:
                    logger.warning("[COMMONS] Refused file over the size cap")
                    return None
                chunks.append(chunk)
    except requests.RequestException as exc:
        logger.warning(f"[COMMONS] Thumbnail fetch failed: {exc}")
        return None

    return b"".join(chunks), content_type



