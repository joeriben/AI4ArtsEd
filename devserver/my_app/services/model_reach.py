"""Which provider reaches which of the register's models, from one file.

config/model_providers.json is generated by scripts/build_model_providers.py
from the providers' catalogues and committed, so an installation offers the
list without asking any provider anything; its 'declared' block is kept by
hand for a model a catalogue names differently than the register does
(config/model_register.json). This reads the two blocks as one answer.
"""
import json
import logging
from pathlib import Path
from typing import Dict

logger = logging.getLogger(__name__)

REACH_FILE = Path(__file__).parent.parent.parent / "config" / "model_providers.json"


def reach() -> Dict[str, Dict[str, str]]:
    """{register name: {provider: the id that provider wants}}, in the file's
    order (which is the register's). 'declared' entries stand beside the
    catalogue's and win where both name a provider: the hand-kept line is the
    one with a source. Read per call, as the register and the matrix are, so
    a changed file shows without a restart. Empty when the file is missing
    or is not the shape above, with a log line -- the list is then this
    installation's own cells alone."""
    try:
        with open(REACH_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as e:
        logger.warning(f"[MODEL-REACH] {REACH_FILE.name} unreadable: {e}")
        return {}
    if not isinstance(data, dict):
        logger.warning(f"[MODEL-REACH] {REACH_FILE.name} is not an object; no reach")
        return {}
    out: Dict[str, Dict[str, str]] = {}
    for block in ("reach", "declared"):
        entries = data.get(block)
        if not isinstance(entries, dict):
            continue
        for name, per_provider in entries.items():
            if not isinstance(per_provider, dict):
                continue
            routes = {p: v.strip() for p, v in per_provider.items()
                      if not p.startswith("_") and isinstance(v, str) and v.strip()}
            if routes:
                out.setdefault(name, {}).update(routes)
    return out
