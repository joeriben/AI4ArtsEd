def _passes_image_check(image: "CommonsImage", safety_level: str) -> Optional[bool]:
    """Show one picture to the platform's own image check.

    ``True`` it may be shown, ``False`` it may not, ``None`` no verdict could be
    obtained. The third is not the second: a checker that is down means the row
    says the archive could not be reached, not that nothing was found.

    The check wants a file on disk, so the bytes are written to a temporary file
    and removed again — nothing from the archive is kept.
    """
    url = decode_image_ref(image.thumb_proxy.rsplit("/", 1)[-1])
    if not url:
        return None
    fetched = fetch_image_bytes(url)
    if not fetched:
        return None

    payload, _ = fetched
    tmp_path = None
    try:
        with tempfile.NamedTemporaryFile(suffix=".img", delete=False) as handle:
            handle.write(payload)
            tmp_path = handle.name
        from my_app.utils.vlm_safety import (vlm_safety_check,
                                              VLM_OPERATIONAL_BLOCK_MESSAGE)
        is_safe, reason, _ = vlm_safety_check(tmp_path, safety_level)
        if not is_safe and reason == VLM_OPERATIONAL_BLOCK_MESSAGE:
            # The check could not run. That is not a judgement about the picture,
            # and the row must not report it as one.
            logger.warning(f"[COMMONS] Image check unavailable for {image.title}")
            return None
        if not is_safe:
            logger.info(f"[COMMONS] Dropped by image check: {image.title} ({reason})")
        return bool(is_safe)
    except Exception as exc:  # noqa: BLE001 - no verdict is not a verdict
        logger.error(f"[COMMONS] Image check failed for {image.title}: {exc}")
        return None
    finally:
        if tmp_path:
            try:
                os.unlink(tmp_path)
            except OSError:
                pass


def _has_left(client_gone: Optional[threading.Event]) -> bool:
    """Whether the page this row is being made for has stopped being read.

    ``None`` wherever no stream carries the answer — the plain POST, and every
    caller inside this module's own tests — and there the work runs to its end
    exactly as it always has.
    """
    return client_gone is not None and client_gone.is_set()


def _pool(candidates: List["CommonsImage"]) -> List["CommonsImage"]:
    """Thin the candidate list to one picture per subject, then shuffle it.

    TWO faults, one cause — the head of a relevance ranking, taken in order.

    The ranking groups: a search for "animal on a street" put "Brown Rat
    (Rattus norvegicus) also called Norway Rat or Common Rat - ..." in first and
    third place, and the forty hits behind them were almost all Rattus
    norvegicus — the ranking of a vague word collapses onto whichever subject
    happens to be catalogued in it most often. Two keys, and one of each stays:
    the first two words of the title, which is what a species and a series
    share, and the author, who uploads in series.

    And the ranking is fixed: the term is derived at temperature 0 and cached,
    Commons ranks deterministically, and the first three that passed the checks
    were therefore the same three for ever. The row is a horizon of photographs
    that already exist; which three of 185 687 stand there is not a finding, and
    holding them still made the archive look as though it held three files.

    Shuffled AFTER the thinning, so a rerun varies over subjects rather than over
    near-copies of one.
    """
    seen_title = set()
    seen_author = set()
    thinned: List["CommonsImage"] = []
    for candidate in candidates:
        title_key = " ".join(candidate.title.lower().split()[:2])
        author_key = candidate.author.strip().lower()
        if title_key in seen_title or (author_key and author_key in seen_author):
            continue
        seen_title.add(title_key)
        if author_key:
            seen_author.add(author_key)
        thinned.append(candidate)
    random.shuffle(thinned)
    return thinned


def _take(candidates: List["CommonsImage"], limit: int,
          safety_level: Optional[str],
          client_gone: Optional[threading.Event] = None
          ) -> Tuple[List["CommonsImage"], bool]:
    """The first ``limit`` candidates that may be shown. Second value: whether a
    verdict was missing for at least one of them.

    Read BETWEEN candidates, never inside one: a check that has begun holds the
    GPU slot it queued for and a temporary file it has to remove, and dropping
    out of the middle of it would leave both. Between two candidates there is
    nothing to leave, and the pair handed back is the pair this function always
    hands back — the row is simply shorter, which is what a row nobody is
    reading is worth.
    """
    if (safety_level or "") not in VLM_CHECKED_LEVELS:
        return candidates[:limit], False
    out: List["CommonsImage"] = []
    unverifiable = False
    for candidate in candidates:
        if len(out) >= limit:
            break
        if _has_left(client_gone):
            logger.info(f"[COMMONS] Reader gone after {len(out)} picture(s); "
                        "the remaining candidates are not checked")
            break
        # The archive's own description first — it is free, and it names things
        # the describing model was measured not to name.
        if _is_explicit(candidate.categories + [candidate.title]):
            logger.info(f"[COMMONS] Dropped by category screen: {candidate.title}")
            continue
        verdict = _passes_image_check(candidate, safety_level or "")
        if verdict is None:
            unverifiable = True
            continue
        if verdict:
            out.append(candidate)
    return out, unverifiable


def _api_get(params: Dict[str, str]) -> Optional[Dict[str, Any]]:
    params = dict(params)
    params["format"] = "json"
    params["formatversion"] = "2"
    try:
        response = requests.get(COMMONS_API, params=params,
                                headers={"User-Agent": USER_AGENT},
                                timeout=HTTP_TIMEOUT)
        response.raise_for_status()
        return response.json()
    except (requests.RequestException, ValueError) as exc:
        logger.warning(f"[COMMONS] API call failed: {exc}")
        return None


# How often the continuation of one answer is followed. MediaWiki caps a batch
# at 500 rows for a client without apihighlimits, and asking 40 files for all
# their categories crosses that on the first answer: the files past the cut come
# back with NO ``categories`` key, which is indistinguishable from a file that
# carries none. Both screens below read that list, so a truncated answer clears
# pictures nobody looked at. Measured on 2026-09-09 for "painting": 500 rows,
# 21 of 40 files with an empty list. Eight rounds cover 4000 rows.
MAX_CONTINUATIONS = 8


def _pages_by_key(pages: Any) -> Dict[str, Dict[str, Any]]:
    """The pages of one answer, keyed the same way in both format versions."""
    if isinstance(pages, dict):
        return {str(key): value for key, value in pages.items()}
    return {str(page.get("pageid") or page.get("title")): page for page in pages}


def _merge_pages(base: Dict[str, Any], addition: Dict[str, Any]) -> None:
    """Fold a continued answer into the first one, page by page.

    A continuation carries only the property that was cut off, so a field
    already present is never overwritten -- only list fields grow.
    """
    base_pages = (base.get("query") or {}).get("pages")
    added_pages = (addition.get("query") or {}).get("pages")
    if base_pages is None or added_pages is None:
        return
    index = _pages_by_key(base_pages)
    for key, page in _pages_by_key(added_pages).items():
        target = index.get(key)
        if target is None:
            if isinstance(base_pages, list):
                base_pages.append(page)
            else:
                base_pages[key] = page
            continue
        for field, value in page.items():
            existing = target.get(field)
            if isinstance(value, list) and isinstance(existing, list):
                existing.extend(value)
            elif field not in target:
                target[field] = value


def _api_get_complete(params: Dict[str, str]) -> Optional[Dict[str, Any]]:
    """Ask, and keep asking while the answer says it is unfinished.

    ``None`` means the archive could not be asked, or could not be asked to the
    end. A caller must not read a truncated answer as a complete one: the
    answer says so itself, in ``continue``, and until 2026-09-09 nothing here
    looked at it.
    """
    merged = _api_get(params)
    if merged is None:
        return None
    rounds = 0
    while merged.get("continue"):
        if rounds >= MAX_CONTINUATIONS:
            logger.warning(f"[COMMONS] Answer still unfinished after {rounds} "
                           "continuations; treating it as unaskable")
            return None
        rounds += 1
        following = _api_get({**params,
                              **{key: str(value)
                                 for key, value in merged["continue"].items()}})
        if following is None:
            return None
        carry = following.get("continue")
        _merge_pages(merged, following)
        if carry:
            merged["continue"] = carry
        else:
            merged.pop("continue", None)
    return merged


def search_images(term: str, limit: int = MAX_IMAGES,
                  safety_level: Optional[str] = None,
                  client_gone: Optional[threading.Event] = None
                  ) -> Optional[Tuple[List[CommonsImage], bool]]:
    """Search Commons and return up to ``limit`` usable files.

    ``None`` means the archive could not be asked. Otherwise ``(images, unverifiable)``:
    an empty list means it was asked and holds nothing for this term, and
    ``unverifiable`` says whether a picture was withheld because no safety verdict
    could be obtained rather than because none was found. The row says different
    things about all three.

    ``filetype:bitmap`` keeps PDFs and scanned books out — without it several
    result lists in the 2026-03-22 probe were dominated by books. The
    ``-incategory`` clauses drop the obvious AI categories at query time; the
    per-file category check below catches the rest. The death words and
    categories are never asked for at all (``DEATH_EXCLUDED_WORDS``).
    """
    term = (term or "").strip()
    if not term:
        return [], False

    # Keyed on the term alone: the cache holds the UNCHECKED candidate list, and
    # both the count and the safety verdict are applied to it afterwards. Keying
    # it on limit as well would have pinned a one-image answer to the term.
    cached = _search_cache.get(term)
    if cached is not None:
        return _take(_pool([CommonsImage(**item) for item in cached]), limit,
                     safety_level, client_gone)

    excluded = " ".join(f'-incategory:"{name}"' for name in AI_EXCLUDED_CATEGORIES)
    no_death = " ".join(
        [f"-{word}" for word in DEATH_EXCLUDED_WORDS]
        + [f'-incategory:"{name}"' for name in DEATH_EXCLUDED_CATEGORIES]
    )
    query = f"{term} filetype:bitmap {excluded} {no_death}"

    # Ask for more than we need: AI files and files without a usable thumbnail
    # are dropped afterwards.
    found = _api_get({
        "action": "query",
        "list": "search",
        "srsearch": query,
        "srnamespace": "6",
        "srlimit": str(SEARCH_RESULTS),
    })
    if found is None:
        return None

    titles = [hit["title"] for hit in found.get("query", {}).get("search", [])]
    if not titles:
        logger.info(f"[COMMONS] Nothing found for {term!r}")
        _search_cache.set(term, [])
        return [], False

    # To the end, not to the first 500 rows: the category list is what both
    # screens below read, and a cut-off list arrives looking like an empty one.
    detail = _api_get_complete({
        "action": "query",
        "titles": "|".join(titles),
        "prop": "imageinfo|categories",
        "iiprop": "url|extmetadata|mime|size",
        "iiurlwidth": str(THUMB_WIDTH),
        "cllimit": "max",
    })
    if detail is None:
        return None

    by_title = {page.get("title"): page for page in detail.get("query", {}).get("pages", [])}

    images: List[CommonsImage] = []
    for title in titles:
        if len(images) >= MAX_CHECK_CANDIDATES:
            break
        page = by_title.get(title)
        if not page:
            continue
        info_list = page.get("imageinfo") or []
        if not info_list:
            continue
        info = info_list[0]
        if (info.get("mime") or "").lower() not in ALLOWED_IMAGE_TYPES:
            continue
        thumb = info.get("thumburl")
        if not thumb:
            continue
        # The description page is where author and licence can be checked. A file
        # without one cannot carry its own attribution, and an empty href would
        # reopen this very page in a new tab.
        file_page = info.get("descriptionurl") or ""
        if not file_page:
            logger.info(f"[COMMONS] Dropped file without description page: {title}")
            continue

        categories = [c.get("title", "").replace("Category:", "", 1)
                      for c in page.get("categories", [])]
        meta = info.get("extmetadata") or {}
        author = _strip_html(meta.get("Artist", {}).get("value", ""))
        licence = _strip_html(meta.get("LicenseShortName", {}).get("value", ""))
        if not author:
            author = _strip_html(meta.get("Credit", {}).get("value", ""))

        # The licence goes into the same test as the categories: PD-algorithm is
        # a licence, not a category, and it marks a work with no human author.
        if _is_ai_generated(categories + [title, licence]):
            logger.info(f"[COMMONS] Dropped AI-generated file: {title}")
            continue

        images.append(CommonsImage(
            title=title.replace("File:", "", 1),
            thumb_proxy=f"{IMAGE_ROUTE}/{encode_image_ref(thumb)}",
            width=int(info.get("thumbwidth") or 0),
            height=int(info.get("thumbheight") or 0),
            author=author,
            licence=licence,
            file_page=file_page,
            # The tile shows three; the screen reads them all, so the full
            # list travels and the trimming happens where it is displayed.
            categories=categories,
        ))

    _search_cache.set(term, [asdict(image) for image in images])
    logger.info(f"[COMMONS] {len(images)} candidate(s) for {term!r}")
    return _take(_pool(images), limit, safety_level, client_gone)


def lookup_for_prompt(prompt: str, limit: int = MAX_IMAGES,
                      safety_level: Optional[str] = None,
                      client_gone: Optional[threading.Event] = None
                      ) -> Dict[str, Any]:
    """The whole step for one prompt: term, then images.

    ``state`` is ``ok``, ``no_motif``, ``nothing_found`` or ``error``. The first
    three are ordinary answers and the row shows each differently; ``error`` is
    the only one that says something about US rather than about the prompt.

    ``client_gone`` is the leaving signal of the streamed transport, handed down
    to the picture checks; ``None`` where no stream carries the answer.
    """
    term, status = derive_search_term(prompt)
    if status == TERM_UNAVAILABLE:
        return {"state": "error", "term": None, "images": []}
    if status == TERM_NO_MOTIF or not term:
        return {"state": "no_motif", "term": None, "images": []}

    result = search_images(term, limit=limit, safety_level=safety_level,
                           client_gone=client_gone)
    if result is None:
        return {"state": "error", "term": term, "images": []}

    images, unverifiable = result

    # A faithful three-noun term is more specific than the archive often is:
    # "grandparents family meal" answered with one file where "grandparents meal"
    # answered with three. So the third noun is dropped once, and the SHORTER
    # term is what the row then shows — the closing line claims the pictures were
    # found with the term above it, and that has to stay true.
    #
    # Not once the reader has gone. The widening exists for a row that came back
    # empty BECAUSE the term was too narrow, and a row that came back empty
    # because nobody is reading it any more is not that row: widening it would
    # ask the archive a second time and start a second set of picture checks for
    # a page that is closed.
    if not images and not unverifiable and not _has_left(client_gone):
        content = [w for w in term.split(" ") if w not in TERM_FUNCTION_WORDS]
        shorter = " ".join(content[:2])
        if shorter != term:
            logger.info(f"[COMMONS] {term!r} found nothing, widening to {shorter!r}")
            widened = search_images(shorter, limit=limit,
                                    safety_level=safety_level,
                                    client_gone=client_gone)
            if widened is not None and widened[0]:
                term, (images, unverifiable) = shorter, widened

    if not images:
        # A row that is empty because no picture could be CHECKED is not a row
        # that is empty because nothing was found.
        state = "error" if unverifiable else "nothing_found"
        return {"state": state, "term": term, "images": []}

    return {"state": "ok", "term": term, "images": [asdict(i) for i in images]}
